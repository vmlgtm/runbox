import fs from "node:fs";
import path from "node:path";
import type { DiscoveryResult } from "./route-discovery.js";
import { discoverProject } from "./route-discovery.js";

export interface InitResult {
  configPath: string;
  skillPath: string;
  discovery: DiscoveryResult;
}

/**
 * Generates `runbox.config.ts` and `.agents/skills/runbox/SKILL.md`
 * inside `cwd` based on static auto-discovery.
 */
export function initProject(
  cwd: string,
  options: { overwrite?: boolean } = {}
): InitResult {
  const resolvedCwd = path.resolve(cwd);
  const configPath = path.join(resolvedCwd, "runbox.config.ts");

  if (fs.existsSync(configPath) && !options.overwrite) {
    throw new Error(
      `runbox.config.ts already exists in ${resolvedCwd}. Pass --force to overwrite.`
    );
  }

  const discovery = discoverProject(resolvedCwd);
  const configContent = renderRunboxConfigTs(discovery);
  fs.writeFileSync(configPath, configContent, "utf8");

  const skillDir = path.join(resolvedCwd, ".agents", "skills", "runbox");
  fs.mkdirSync(skillDir, { recursive: true });
  const skillPath = path.join(skillDir, "SKILL.md");
  fs.writeFileSync(skillPath, renderAgentSkillMd(), "utf8");

  return { configPath, skillPath, discovery };
}

export function renderRunboxConfigTs(discovery: DiscoveryResult): string {
  const featuresBody =
    discovery.features.length > 0
      ? discovery.features
          .map((f) => {
            const lines = [
              `    {`,
              `      id: ${JSON.stringify(f.id)},`,
              `      name: ${JSON.stringify(f.name)},`,
              `      route: ${JSON.stringify(f.route)},`,
            ];
            if (f.sampleRoute) {
              lines.push(`      sampleRoute: ${JSON.stringify(f.sampleRoute)},`);
            }
            lines.push(`      files: ${JSON.stringify(f.files)},`);
            lines.push(`    },`);
            return lines.join("\n");
          })
          .join("\n")
      : `    {\n      id: "home",\n      name: "Home",\n      route: "/",\n      files: ["src/**"],\n    },`;

  const guardrailsJson = JSON.stringify(discovery.guardrails, null, 2)
    .split("\n")
    .map((line, i) => (i === 0 ? line : `  ${line}`))
    .join("\n");

  const aliasesJson = JSON.stringify(discovery.aliases, null, 2)
    .split("\n")
    .map((line, i) => (i === 0 ? line : `  ${line}`))
    .join("\n");

  const serverJson = JSON.stringify(discovery.server, null, 2)
    .split("\n")
    .map((line, i) => (i === 0 ? line : `  ${line}`))
    .join("\n");

  return `import { defineConfig } from "runbox";

// Auto-generated by \`runbox init\` (detected framework: ${discovery.framework})
export default defineConfig({
  framework: ${JSON.stringify(discovery.framework)},
  server: ${serverJson},
  aliases: ${aliasesJson},
  guardrails: ${guardrailsJson},
  invariants: {
    noConsoleErrors: true,
    noUncaughtExceptions: true,
    noHydrationMismatch: true,
    noServer5xx: true,
  },
  features: [
${featuresBody}
  ],
});
`;
}

function renderAgentSkillMd(): string {
  return `---
name: runbox
description: Verify code changes deterministically with runbox guardrails, runtime telemetry traps, and property-based UI fuzzing before completing tasks.
---

# Verification Workflow with \`runbox\`

After editing files in this repository, **always verify your diff using \`runbox\`** instead of assuming \`tsc\` or unit tests alone prove runtime correctness.

## 1. Pre-flight static guardrails & affected features
\`\`\`bash
npx runbox check --diff --agent
\`\`\`
- If \`guardrailViolations\` is non-empty, read each violation's \`remediation\` field and fix the architectural root cause.

## 2. Runtime verification & property fuzzing
\`\`\`bash
npx runbox verify --diff --fuzz --agent
\`\`\`
- When verification fails, inspect the compact JSON output:
  - \`violatedInvariant\`: exact error, console/hydration failure, HTTP 5xx, or business invariant broken
  - \`seed\` & \`replayCommand\`: deterministic replay seed
  - \`minimalReproductionSteps\`: shrunk interaction sequence that triggers the bug
- Fix the underlying bug in source code (never suppress errors or add timer workarounds) and re-run \`replayCommand\` until \`status\` is \`"passed"\`.

## 3. Enriching new features
When adding a new user flow, register or update its \`journey\`, \`assertInvariants\`, and \`fuzz.scopeSelector\` in \`runbox.config.ts\`. Use \`npx runbox discover <route>\` to inspect interactive selectors on a page.
`;
}
